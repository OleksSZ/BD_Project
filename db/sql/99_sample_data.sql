SELECT i.id, s.name, s.code, s.lvl, s.name || ' (' || i.short_name || ')',
       'спеціальності', 'УД', (i.edbo_code % 1000 * 7 + ascii(s.code))::text,
       CASE (i.id + ascii(s.code)) % 3 WHEN 0 THEN '01.07.2024' WHEN 1 THEN '01.07.2027' ELSE '31.12.2029' END,
       50 + (i.id * 37 + ascii(s.code) * 13) % 400, 'sample'
FROM institutions i
JOIN spec s ON (i.id + ascii(s.code)) % 3 <> 0           -- умовний «розподіл» програм
WHERE i.edbo_code BETWEEN 900001 AND 900014
  AND NOT EXISTS (SELECT 1 FROM institution_specialties x
                  WHERE x.institution_id = i.id AND x.specialty_code = s.code);

