-- ЛР №7. Опис структури БД: CREATE / ALTER / DROP та декларативні обмеження
-- =====================================================================
-- Команди: CREATE DATABASE, CREATE TABLE, NOT NULL, DEFAULT, UNIQUE (стовпця й таблиці),
-- PRIMARY KEY (простий і складений), IDENTITY з початковим значенням (аналог AUTO_INCREMENT=1001),
-- CHECK (стовпця й таблиці), FOREIGN KEY ... ON DELETE / ON UPDATE (RESTRICT, CASCADE, SET NULL),
-- CONSTRAINT <ім'я>, ALTER TABLE (ADD/DROP COLUMN, SET/DROP DEFAULT, SET/DROP NOT NULL, TYPE,
-- ADD/DROP CONSTRAINT, ADD/DROP PRIMARY KEY), RENAME, TRUNCATE, DROP TABLE.
--
-- Структура — зменшена копія таблиць проєкту (область -> місто -> заклад -> програма).
-- Усе виконується в транзакції і наприкінці відкочується (ROLLBACK): у PostgreSQL DDL
-- транзакційний, тож робоча БД не змінюється.
-- Перед кожною навмисною помилкою ставиться SAVEPOINT, після неї — ROLLBACK TO SAVEPOINT,
-- щоб помилка не перервала всю транзакцію.
-- Запуск: python db/lab.py 7
-- =====================================================================

-- == 1. CREATE DATABASE ==
-- Створення окремої БД з кодуванням UTF-8 (у MySQL: CHARACTER SET utf8mb4). Потрібне право CREATEDB.
-- CREATE DATABASE не може виконуватися всередині транзакції, тому стоїть до BEGIN.
CREATE DATABASE osvita_lab_demo WITH ENCODING 'UTF8' TEMPLATE template0;

-- перевірка: БД з'явилась у системному каталозі (аналог SHOW DATABASES)
SELECT datname, pg_encoding_to_char(encoding) AS encoding, datcollate
FROM   pg_database WHERE datname = 'osvita_lab_demo';

-- видалення БД
DROP DATABASE osvita_lab_demo;

-- == 2. CREATE TABLE з обмеженнями ==
BEGIN;

-- Довідник областей: PRIMARY KEY + UNIQUE + NOT NULL.
-- GENERATED ALWAYS AS IDENTITY (START WITH 1) — стандартний SQL-аналог AUTO_INCREMENT
CREATE TABLE lab_regions (
    id    INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100) NOT NULL UNIQUE
);

-- Міста: UNIQUE на рівні ТАБЛИЦІ (пара полів), FK з правилами ON UPDATE CASCADE / ON DELETE RESTRICT
CREATE TABLE lab_cities (
    id         INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    region_id  INTEGER      NOT NULL,
    name       VARCHAR(100) NOT NULL,
    CONSTRAINT uq_lab_city UNIQUE (region_id, name),
    CONSTRAINT fk_lab_city_region FOREIGN KEY (region_id)
        REFERENCES lab_regions (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Заклади: лічильник з 1001 (аналог AUTO_INCREMENT=1001), DEFAULT, CHECK стовпця,
-- CHECK таблиці (умова на кількох полях), FK у формі стовпця з ON DELETE SET NULL
CREATE TABLE lab_institutions (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    edbo_code     INTEGER      NOT NULL UNIQUE,
    name          VARCHAR(300) NOT NULL,
    ownership     VARCHAR(20)  NOT NULL DEFAULT 'Державна'
                  CONSTRAINT ck_lab_ownership CHECK (ownership IN ('Державна', 'Комунальна', 'Приватна')),
    founded_year  INTEGER      CHECK (founded_year BETWEEN 800 AND 2100),
    rating_total  INTEGER      CHECK (rating_total >= 0),
    city_position INTEGER,
    city_id       INTEGER      REFERENCES lab_cities (id) ON UPDATE CASCADE ON DELETE SET NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- обмеження кортежу: позиція в рейтингу міста можлива лише разом із загальним балом
    CONSTRAINT ck_lab_position_needs_total CHECK (city_position IS NULL OR rating_total IS NOT NULL)
);

-- Довідник спеціальностей: природний первинний ключ (код)
CREATE TABLE lab_specialties (
    code  VARCHAR(10) PRIMARY KEY,
    name  TEXT        NOT NULL
);

-- Зв'язок M:N «заклад – спеціальність»: СКЛАДЕНИЙ первинний ключ із двох зовнішніх ключів.
-- Слабка сутність: при видаленні закладу її рядки видаляються (CASCADE)
CREATE TABLE lab_programs (
    institution_id  INTEGER     NOT NULL REFERENCES lab_institutions (id) ON UPDATE CASCADE ON DELETE CASCADE,
    specialty_code  VARCHAR(10) NOT NULL REFERENCES lab_specialties (code) ON UPDATE CASCADE ON DELETE RESTRICT,
    students_count  INTEGER     NOT NULL DEFAULT 0 CHECK (students_count >= 0),
    PRIMARY KEY (institution_id, specialty_code)
);

-- структура таблиці з каталогу (аналог DESCRIBE / SHOW COLUMNS у MySQL)
SELECT column_name, data_type, character_maximum_length AS len, is_nullable, column_default
FROM   information_schema.columns
WHERE  table_name = 'lab_institutions'
ORDER  BY ordinal_position;

-- усі обмеження створених таблиць з їх визначенням (аналог SHOW CREATE TABLE)
SELECT conrelid::regclass AS table_name, conname, contype, pg_get_constraintdef(oid) AS definition
FROM   pg_constraint
WHERE  conrelid::regclass::text LIKE 'lab\_%'
ORDER  BY 1, contype, conname;

-- == 3. Перевірка обмежень командами INSERT ==
INSERT INTO lab_regions (name) VALUES ('м. Київ'), ('Львівська область');
INSERT INTO lab_cities (region_id, name) VALUES (1, 'Київ'), (2, 'Львів');
INSERT INTO lab_specialties VALUES ('121', 'Інженерія програмного забезпечення'), ('122', 'Комп’ютерні науки');

-- коректний рядок: ownership і created_at беруться з DEFAULT, id — з лічильника (1001)
INSERT INTO lab_institutions (edbo_code, name, founded_year, rating_total, city_position, city_id)
VALUES (41, 'КНУ імені Тараса Шевченка', 1834, 980, 1, 1)
RETURNING id, ownership, created_at IS NOT NULL AS has_created_at;

SAVEPOINT sp;
-- очікувана помилка: NOT NULL — назву не вказано
INSERT INTO lab_institutions (edbo_code, name) VALUES (42, NULL);
ROLLBACK TO SAVEPOINT sp;

-- очікувана помилка: UNIQUE — такий код ЄДЕБО вже є
INSERT INTO lab_institutions (edbo_code, name) VALUES (41, 'Дублікат');
ROLLBACK TO SAVEPOINT sp;

-- очікувана помилка: CHECK стовпця — недопустима форма власності
INSERT INTO lab_institutions (edbo_code, name, ownership) VALUES (43, 'Тест', 'Акціонерна');
ROLLBACK TO SAVEPOINT sp;

-- очікувана помилка: CHECK таблиці — позиція в місті без загального балу
INSERT INTO lab_institutions (edbo_code, name, city_position) VALUES (44, 'Тест', 5);
ROLLBACK TO SAVEPOINT sp;

-- очікувана помилка: FOREIGN KEY — міста з id = 99 не існує
INSERT INTO lab_institutions (edbo_code, name, city_id) VALUES (45, 'Тест', 99);
ROLLBACK TO SAVEPOINT sp;

-- очікувана помилка: складений PRIMARY KEY — програма закладу за цією спеціальністю вже є
INSERT INTO lab_programs VALUES (1001, '121', 100), (1001, '121', 50);
ROLLBACK TO SAVEPOINT sp;

-- id буде не 1002: невдалі INSERT вище вже «витратили» значення лічильника,
-- а ROLLBACK лічильник (послідовність) не повертає
INSERT INTO lab_institutions (edbo_code, name, founded_year, city_id)
VALUES (46, 'Львівська політехніка', 1816, 2)
RETURNING id;

-- тому id беремо не «вручну», а підзапитом за природним ключем
INSERT INTO lab_programs
SELECT i.id, p.code, p.students
FROM  (VALUES (41, '121', 120), (41, '122', 90), (46, '121', 70)) AS p(edbo, code, students)
JOIN   lab_institutions i ON i.edbo_code = p.edbo;

-- == 4. Дія правил посилальної цілісності ==
-- ON UPDATE CASCADE: зміна коду спеціальності автоматично змінює його в lab_programs
UPDATE lab_specialties SET code = '121-new' WHERE code = '121';
SELECT * FROM lab_programs ORDER BY institution_id, specialty_code;

SAVEPOINT sp;
-- очікувана помилка: ON DELETE RESTRICT — область, у якій є міста, видалити не можна
DELETE FROM lab_regions WHERE name = 'Львівська область';
ROLLBACK TO SAVEPOINT sp;

-- ON DELETE SET NULL: місто видалено -> у закладу city_id стає NULL
DELETE FROM lab_cities WHERE name = 'Львів';
SELECT id, name, city_id FROM lab_institutions ORDER BY id;

-- ON DELETE CASCADE: заклад видалено -> його програми видаляються разом з ним
DELETE FROM lab_institutions WHERE edbo_code = 41;
SELECT * FROM lab_programs;

-- == 5. ALTER TABLE: зміна структури ==
-- додати стовпець (NULL дозволено)
ALTER TABLE lab_institutions ADD COLUMN website VARCHAR(200);

-- змінити тип стовпця (у MySQL: MODIFY COLUMN)
ALTER TABLE lab_institutions ALTER COLUMN website TYPE VARCHAR(500);

-- встановити й прибрати значення за замовчуванням
ALTER TABLE lab_institutions ALTER COLUMN website SET DEFAULT 'https://';
ALTER TABLE lab_institutions ALTER COLUMN website DROP DEFAULT;

-- зробити стовпець обов'язковим і повернути назад
ALTER TABLE lab_institutions ALTER COLUMN founded_year SET NOT NULL;
ALTER TABLE lab_institutions ALTER COLUMN founded_year DROP NOT NULL;

-- додати іменоване обмеження і видалити його за ім'ям
ALTER TABLE lab_institutions ADD CONSTRAINT ck_lab_site CHECK (website LIKE 'http%');
ALTER TABLE lab_institutions DROP CONSTRAINT ck_lab_site;

-- видалити й заново додати первинний ключ (ім'я PK за замовчуванням: <таблиця>_pkey)
ALTER TABLE lab_specialties DROP CONSTRAINT lab_specialties_pkey CASCADE;
ALTER TABLE lab_specialties ADD PRIMARY KEY (code);

-- додати зовнішній ключ до існуючої таблиці і видалити його
ALTER TABLE lab_programs ADD CONSTRAINT fk_lab_prog_spec
    FOREIGN KEY (specialty_code) REFERENCES lab_specialties (code) ON UPDATE CASCADE;
ALTER TABLE lab_programs DROP CONSTRAINT fk_lab_prog_spec;

-- перезапустити лічильник з нового значення (аналог ALTER TABLE ... AUTO_INCREMENT = 2001)
ALTER TABLE lab_institutions ALTER COLUMN id RESTART WITH 2001;
INSERT INTO lab_institutions (edbo_code, name) VALUES (47, 'Новий заклад') RETURNING id;

-- перейменувати стовпець і таблицю
ALTER TABLE lab_institutions RENAME COLUMN website TO site_url;
ALTER TABLE lab_specialties RENAME TO lab_specialty_dict;

-- видалити стовпець
ALTER TABLE lab_institutions DROP COLUMN site_url;

-- == 6. TRUNCATE і DROP ==
-- TRUNCATE: швидко очистити таблицю та скинути лічильник (CASCADE — і залежні таблиці)
TRUNCATE TABLE lab_institutions RESTART IDENTITY CASCADE;
SELECT count(*) AS rows_after_truncate FROM lab_institutions;

-- DROP TABLE: видалити таблиці (CASCADE — разом із залежними обмеженнями)
DROP TABLE lab_programs, lab_specialty_dict, lab_institutions, lab_cities, lab_regions CASCADE;

ROLLBACK;
